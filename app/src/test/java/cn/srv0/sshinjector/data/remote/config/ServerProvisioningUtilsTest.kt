package cn.srv0.sshinjector.data.remote.config

import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * 2026-11-25 真机/代码复核: 向导生成的公钥 comment 是 `android-generated@<Date()>`,
 * `Date().toString()` 含空格 → 旧校验按 `\s+` 切分得到 7+ 段 → 恒判"公钥格式非法",
 * 一键配置永远无法完成。校验只约束前两个 token, comment 允许任意非换行文本。
 */
class ServerProvisioningUtilsTest {
    private val body = "AAAAC3NzaC1lZDI1NTE5AAAAIG2K1rQwC0kQhVtBzQyXb3b1b3b1b3b1b3b1b3b1b3b1"

    @Test
    fun `spaced comment generated by the app is accepted`() {
        val key = "ssh-ed25519 $body android-generated@Wed Nov 25 12:34:56 GMT 2026"
        assertTrue(isValidPublicKey(key))
    }

    @Test
    fun `key without comment is accepted`() {
        assertTrue(isValidPublicKey("ssh-ed25519 $body"))
    }

    @Test
    fun `newline injection is still rejected`() {
        assertFalse(isValidPublicKey("ssh-ed25519 $body comment\ncommand=\"rm -rf /\" ssh-ed25519 $body"))
    }

    @Test
    fun `command prefix is rejected by algorithm whitelist`() {
        assertFalse(isValidPublicKey("command=\"x\" ssh-ed25519 $body"))
    }

    @Test
    fun `control characters in comment are rejected`() {
        assertFalse(isValidPublicKey("ssh-ed25519 $body bad\u0000comment"))
    }
}
